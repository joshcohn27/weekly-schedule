import { useEffect, useState } from 'react';
import type { SessionWeeks } from '../autogen/config';

export type AutoGenerateMode = 'fill-empty' | 'replace-all';

interface Props {
  /** 1-based number of the week being generated. */
  weekNumber: number;
  /** Does the week already have any activities in it? */
  hasActivities: boolean;
  onCancel: () => void;
  onGenerate: (mode: AutoGenerateMode, sessionWeeks: SessionWeeks) => void;
}

/** Confirm dialog for Auto generate: asks what to do with what is already filled in, and how long the session is. */
export default function AutoGenerateDialog({ weekNumber, hasActivities, onCancel, onGenerate }: Props) {
  const [mode, setMode] = useState<AutoGenerateMode>('fill-empty');
  const [sessionWeeks, setSessionWeeks] = useState<SessionWeeks>(4);

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape') onCancel();
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [onCancel]);

  const title = `Auto generate Week ${weekNumber}?`;
  return (
    <div className="modal-backdrop" onMouseDown={(e) => e.target === e.currentTarget && onCancel()}>
      <div className="modal" role="dialog" aria-modal="true" aria-labelledby="autogen-title">
        <h2 id="autogen-title">{title}</h2>
        <p>
          This builds a full schedule for Week {weekNumber} from the bunks on the Build tab. It reads the other weeks you have
          loaded, so each bunk&apos;s totals stay fair across the whole session. Every time you run it you get a different valid
          schedule, so you can keep regenerating until you like one.
        </p>

        {hasActivities && (
          <fieldset>
            <legend>Week {weekNumber} already has activities in it. What should happen to them?</legend>
            <label>
              <input type="radio" name="autogen-mode" checked={mode === 'fill-empty'} onChange={() => setMode('fill-empty')} /> Keep what
              is already filled in and only fill the empty cells. Best if you already placed events like All-Camp Event or Village Day.
            </label>
            <label>
              <input type="radio" name="autogen-mode" checked={mode === 'replace-all'} onChange={() => setMode('replace-all')} /> Replace
              everything in Week {weekNumber}. All existing activities in this week are cleared first.
            </label>
          </fieldset>
        )}

        <p>
          <label>
            Session length{' '}
            <select value={sessionWeeks} onChange={(e) => setSessionWeeks(Number(e.target.value) === 3 ? 3 : 4)}>
              <option value={4}>4 weeks (Mohawk plays MNL)</option>
              <option value={3}>3 weeks (Mohawk plays MAL)</option>
            </select>
          </label>
        </p>

        <div className="modal-buttons">
          <button type="button" onClick={onCancel}>
            Cancel
          </button>{' '}
          <button type="button" className="primary" autoFocus onClick={() => onGenerate(hasActivities ? mode : 'replace-all', sessionWeeks)}>
            Generate
          </button>
        </div>
      </div>
    </div>
  );
}
